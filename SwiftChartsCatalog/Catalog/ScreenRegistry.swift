/// What makes a catalog screen exist: the code regions it shows and the view that draws it.
struct ScreenRegistration {
    let snippets: [SnippetReference]
    let makeView: (CatalogScreen) -> AnyView

    init(snippets: [SnippetReference], @ViewBuilder view: @escaping (CatalogScreen) -> some View) {
        self.snippets = snippets
        makeView = { AnyView(view($0)) }
    }
}

